//go:build ignore

// gen downloads one release of the SPDX license list and writes the license
// and exception identifiers that spdx.go embeds, one per line.
//
//	go run gen.go v3.29.0
package main

import (
	"encoding/json"
	"fmt"
	"log"
	"net/http"
	"os"
	"slices"
	"strings"
	"time"
)

const base = "https://raw.githubusercontent.com/spdx/license-list-data/"

func main() {
	if len(os.Args) != 2 || !strings.HasPrefix(os.Args[1], "v") {
		log.Fatal("usage: go run gen.go <license-list-data tag, e.g. v3.29.0>")
	}
	tag := os.Args[1]
	var lic struct {
		Version  string `json:"licenseListVersion"`
		Licenses []struct {
			ID string `json:"licenseId"`
		} `json:"licenses"`
	}
	var exc struct {
		Exceptions []struct {
			ID string `json:"licenseExceptionId"`
		} `json:"exceptions"`
	}
	fetch(base+tag+"/json/licenses.json", &lic)
	fetch(base+tag+"/json/exceptions.json", &exc)
	var ids, excIDs []string
	for _, l := range lic.Licenses {
		ids = append(ids, l.ID)
	}
	for _, e := range exc.Exceptions {
		excIDs = append(excIDs, e.ID)
	}
	write("licenses.txt", lic.Version, ids)
	write("exceptions.txt", lic.Version, excIDs)
}

func fetch(url string, v any) {
	c := &http.Client{Timeout: 30 * time.Second}
	resp, err := c.Get(url)
	if err != nil {
		log.Fatal(err)
	}
	defer resp.Body.Close()
	if resp.StatusCode != http.StatusOK {
		log.Fatalf("%s: %s", url, resp.Status)
	}
	if err := json.NewDecoder(resp.Body).Decode(v); err != nil {
		log.Fatalf("%s: %v", url, err)
	}
}

func write(name, version string, ids []string) {
	if len(ids) == 0 {
		log.Fatalf("%s: no identifiers", name)
	}
	slices.Sort(ids)
	content := fmt.Sprintf("# SPDX License List %s, generated by gen.go. Do not edit.\n%s\n", version, strings.Join(ids, "\n"))
	if err := os.WriteFile(name, []byte(content), 0o644); err != nil {
		log.Fatal(err)
	}
}
